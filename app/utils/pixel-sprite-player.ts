/**
 * High-resolution player sprite bank for the 2.5D world of Willow Hollow.
 *
 * Conventions (for the renderer):
 * - Every frame is a 32x40 grid: 40 rows of 32 characters. The renderer
 *   anchors the sprite at its base row and centers it horizontally.
 * - Each character maps to a color in `PLAYER_PALETTE`; `.` is transparent.
 * - The silhouette carries a hard 2px near-black plum outline. Internal
 *   contours (arm seams, leg splits, tunic hem) are 1px so the limbs stay
 *   readable at native size. Light falls from the top left; shade piles
 *   into the bottom right.
 * - Six unique walk frames per direction: contact, down, pass, up, contact,
 *   pass. The pass frames lift the whole upper body by 1px while the planted
 *   foot stays on the ground, and the arms counterswing against the legs.
 * - The `side` sprite faces LEFT; mirror it horizontally for right.
 * - `frameMs` is how long one frame is held before advancing. 130ms matches
 *   `playerWalkAnimation` in `world-animation.ts`, so a full stride is 780ms.
 */

